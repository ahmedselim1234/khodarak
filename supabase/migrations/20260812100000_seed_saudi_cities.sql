-- Seed the cities lookup table with the full set of Saudi Arabia's major
-- cities/governorates across all 13 regions, beyond the single "الرياض" row
-- from the Phase 1 migration. `name_ar` has no unique constraint, so
-- de-dupe explicitly rather than relying on ON CONFLICT.

insert into public.cities (name_ar, is_active)
select v.name_ar, true
from (
  values
    -- Riyadh region
    ('الرياض'), ('الخرج'), ('الدوادمي'), ('المجمعة'), ('القويعية'),
    ('وادي الدواسر'), ('الأفلاج'), ('الزلفي'), ('شقراء'), ('حوطة بني تميم'),
