    -- Najran region
    ('نجران'), ('شرورة'), ('حبونا'), ('بدر الجنوب'), ('ثار'), ('يدمة'),
    ('خباش'),

    -- Al Bahah region
    ('الباحة'), ('بلجرشي'), ('المندق'), ('المخواة'), ('قلوة'),
    ('العقيق'), ('القرى'), ('بني حسن'),

    -- Al Jouf region
    ('سكاكا'), ('القريات'), ('دومة الجندل'), ('طبرجل')
