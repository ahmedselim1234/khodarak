    ('رماح'), ('السليل'),

    -- Makkah region
    ('مكة المكرمة'), ('جدة'), ('الطائف'), ('رابغ'), ('القنفذة'),
    ('الليث'), ('خليص'), ('الجموم'), ('الكامل'), ('رنية'), ('تربة'),
    ('ميسان'), ('أضم'), ('الخرمة'),

    -- Madinah region
    ('المدينة المنورة'), ('ينبع'), ('العلا'), ('بدر'), ('خيبر'),
    ('مهد الذهب'), ('الحناكية'), ('العيص'), ('وادي الفرع'),

    -- Eastern Province
    ('الدمام'), ('الخبر'), ('الظهران'), ('الأحساء'), ('الجبيل'),
    ('القطيف'), ('الخفجي'), ('حفر الباطن'), ('النعيرية'), ('رأس تنورة'),
    ('بقيق'), ('قرية العليا'),

    -- Qassim region
    ('بريدة'), ('عنيزة'), ('الرس'), ('المذنب'), ('البكيرية'),
    ('البدائع'), ('رياض الخبراء'), ('عيون الجواء'), ('الأسياح'),
    ('النبهانية'), ('ضرية'),

    -- Asir region
    ('أبها'), ('خميس مشيط'), ('بيشة'), ('النماص'), ('محايل عسير'),
    ('سراة عبيدة'), ('ظهران الجنوب'), ('رجال ألمع'), ('تنومة'),
    ('بلقرن'), ('أحد رفيدة'),

    -- Tabuk region
    ('تبوك'), ('الوجه'), ('ضباء'), ('تيماء'), ('أملج'), ('حقل'), ('البدع'),

    -- Hail region
    ('حائل'), ('بقعاء'), ('الشنان'), ('الغزالة'), ('موقق'), ('الشملي'),

